#!/usr/bin/env python3
"""Build the Use cases tab from one data file.

    python3 scripts/build_use_cases.py

Reads scripts/use_cases.json and writes:
  * snippets/ask-o-menu.jsx      the interactive menu (filters, search, copy)
  * use-cases/<type>.mdx         one static page per form of intelligence, so
                                 every prompt is also searchable and readable
                                 by AI assistants (the menu renders in the
                                 browser only, so it is invisible to both)
  * the "Use cases" tab in docs.json

Edit the JSON, never the generated files.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "scripts" / "use_cases.json").read_text())

TYPES = [
    ("meeting", "Meetings", "meetings", "Walk into every room knowing who is there, what has changed for them, and what connects you."),
    ("diligence", "Due diligence", "due-diligence", "Get the picture behind a company or a person, and the people in your network who can give you an honest read."),
    ("access", "Access", "access", "Find the warm path to a person, a firm or a fund, and know which paths not to use."),
    ("discovery", "Discovery", "discovery", "Find the right people in your network, or one introduction away, for what you are doing now."),
    ("network", "Network intelligence", "network-intelligence", "Understand your own network: what changed, who to reconnect with, where it is strong and where it is thin."),
]
PERSONAS = [("any", "Everyone"), ("investor", "Investor"), ("founder", "Founder"),
            ("corp dev", "Corp dev"), ("HR", "HR"), ("sales", "Sales")]
PLABEL = dict(PERSONAS)


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def who(personas):
    named = [PLABEL[p] for p in personas if p != "any"]
    return ", ".join(named) if named else "Everyone"


def write_pages():
    out = ROOT / "use-cases"
    out.mkdir(exist_ok=True)
    for key, label, page, intro in TYPES:
        cases = [d for d in DATA if d["type"] == key]
        lines = ["---", f'title: "{label}"', f'description: "{intro}"', "---", "",
                 "Each prompt is ready to paste into Ask O. Swap the bracketed parts for your own, "
                 "and mention people and companies with `@` so O finds them in your network.", ""]
        for d in cases:
            lines += [f"## {d['title']}", "",
                      f"**For:** {who(d['personas'])}. **When:** {d['when']}", "",
                      "```text wrap", d["prompt"], "```", ""]
            if d.get("youtube"):
                lines += ["<Frame caption=\"The run, recorded in O (other people's names and photos blurred)\">",
                          f'  <iframe className="w-full aspect-video rounded-xl" src="https://www.youtube-nocookie.com/embed/{d["youtube"]}?rel=0" '
                          f'title="{d["title"]}" frameBorder="0" allow="accelerometer; clipboard-write; encrypted-media; gyroscope; picture-in-picture" allowFullScreen></iframe>',
                          "</Frame>", ""]
            lines += [
                      f"**What O does that a search can't:** {d['why']} **Time saved:** {d['saved']}.", ""]
        lines.append("Browse every use case on one page, with filters: [the Ask O menu](/use-cases/index).")
        (out / f"{page}.mdx").write_text("\n".join(lines) + "\n")


def write_snippet():
    data = [{"t": d["type"], "p": d["personas"], "n": d["title"], "w": d["when"], "pr": d["prompt"],
             "why": d["why"], "saved": d["saved"], "id": slug(d["title"]), "yt": d.get("youtube")} for d in DATA]
    types = [[k, l, p] for k, l, p, _ in TYPES]
    jsx = """// Generated by scripts/build_use_cases.py from scripts/use_cases.json. Do not edit by hand.
export const AskOMenu = () => {
  const DATA = %s;
  const TYPES = %s;
  const PERSONAS = %s;
  const [type, setType] = useState("all");
  const [persona, setPersona] = useState("any");
  const [q, setQ] = useState("");
  const [copied, setCopied] = useState("");
  const needle = q.trim().toLowerCase();
  const list = DATA.filter((d) =>
    (type === "all" || d.t === type) &&
    (persona === "any" || d.p.includes(persona) || d.p.includes("any")) &&
    (!needle || (d.n + " " + d.w + " " + d.pr).toLowerCase().includes(needle)));
  const typeOf = (k) => TYPES.find((t) => t[0] === k);
  const who = (p) => { const n = p.filter((x) => x !== "any").map((x) => (PERSONAS.find((y) => y[0] === x) || [x, x])[1]); return n.length ? n.join(", ") : "Everyone"; };
  const fmt = (s) => s.split(/(\\[[^\\]]+\\])/g).map((part, i) =>
    part.startsWith("[") ? <b key={i} className="aom-ph">{part}</b> : part);
  const copy = (d) => { try { navigator.clipboard.writeText(d.pr).then(() => { setCopied(d.id); setTimeout(() => setCopied(""), 1500); }); } catch (e) {} };
  const chip = (on) => "aom-chip" + (on ? " on" : "");
  const pchip = (on) => "aom-pchip" + (on ? " on" : "");
  return (
    <div className="not-prose">
      <div className="flex flex-wrap gap-2 mb-3">
        <button className={chip(type === "all")} onClick={() => setType("all")}>All</button>
        {TYPES.map((t) => <button key={t[0]} className={chip(type === t[0])} onClick={() => setType(t[0])}>{t[1]}</button>)}
      </div>
      <div className="flex flex-wrap items-center gap-2 mb-3">
        {PERSONAS.map((p) => <button key={p[0]} className={pchip(persona === p[0])} onClick={() => setPersona(p[0])}>{p[1]}</button>)}
        <input type="search" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search use cases and prompts" className="aom-search" />
      </div>
      <p className="aom-count">{list.length} of {DATA.length} use cases</p>
      {list.length === 0 ? <p className="aom-count">Nothing matches. Try another word.</p> : null}
      <div className="grid gap-4 sm:grid-cols-2">
        {list.map((d) => (
          <div key={d.id} className="aom-card">
            <div className="flex items-center justify-between gap-2">
              <a href={"/use-cases/" + typeOf(d.t)[2] + "#" + d.id} className="aom-tag">{typeOf(d.t)[1]}</a>
              <span className="aom-who">{who(d.p)}</span>
            </div>
            <h3 className="aom-title">{d.n}</h3>
            <p className="aom-when">{d.w}</p>
            <div className="aom-prompt">{fmt(d.pr)}</div>
            <p className="aom-why"><b>What O does that a search can't:</b> {d.why} <b>Saved:</b> {d.saved}</p>
            <div className="aom-actions">
              <button onClick={() => copy(d)} className="aom-copy">{copied === d.id ? "Copied" : "Copy prompt"}</button>
              {d.yt ? <a href={"https://www.youtube.com/watch?v=" + d.yt} target="_blank" rel="noopener" className="aom-watch">Watch the run</a> : null}
            </div>
          </div>
        ))}
      </div>
    </div>
  );
};
""" % (json.dumps(data, ensure_ascii=False), json.dumps(types), json.dumps(PERSONAS))
    (ROOT / "snippets").mkdir(exist_ok=True)
    (ROOT / "snippets" / "ask-o-menu.jsx").write_text(jsx)


def write_index():
    cards = "\n".join(
        f'  <Card title="{label}" href="/use-cases/{page}">\n    {intro}\n  </Card>' for _, label, page, intro in TYPES)
    text = f"""---
title: "The Ask O menu"
description: "Use cases and the prompts that run them. Swap the bracketed parts, copy, and paste into Ask O."
mode: "wide"
---

import {{ AskOMenu }} from "/snippets/ask-o-menu.jsx"

Filter by the kind of work and by who you are, or search. Bracketed values are placeholders; mention people and companies with `@` so O finds them in your network.

<AskOMenu />

## By form of intelligence

<CardGroup cols={{2}}>
{cards}
</CardGroup>
"""
    (ROOT / "use-cases" / "index.mdx").write_text(text)


def write_nav():
    cfg_path = ROOT / "docs.json"
    cfg = json.loads(cfg_path.read_text())
    tabs = cfg["navigation"]["tabs"]
    tab = {"tab": "Use cases", "groups": [
        {"group": "Use cases", "pages": ["use-cases/index"] + [f"use-cases/{p}" for _, _, p, _ in TYPES]}]}
    tabs[:] = [t for t in tabs if t["tab"] != "Use cases"]
    docs_at = next(i for i, t in enumerate(tabs) if t["tab"] == "Docs")
    tabs.insert(docs_at + 1, tab)
    cfg_path.write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    write_pages()
    write_snippet()
    write_index()
    write_nav()
    print(f"{len(DATA)} use cases -> snippets/ask-o-menu.jsx, use-cases/*.mdx ({len(TYPES)} pages + index), docs.json")
